/**
 * npm run db:pull — pull all real production data from Supabase into the local embedded database.
 */
import postgres from "postgres";
import { config, localDatabaseUrl } from "./dbtools";
import { getDbOptions } from "../src/lib/db/core";

const TABLES = [
  "auth.users",
  "public.profiles",
  "public.imports",
  "public.companies",
  "public.contacts",
  "public.leads",
  "public.call_activities",
  "public.followups",
  "public.scripts",
  "public.research_requests",
  "public.audit_logs",
];

async function getTableInfo(sql: postgres.Sql, schema: string, table: string): Promise<{ cols: string[]; hasIdentity: boolean }> {
  const rows = await sql`
    SELECT column_name, identity_generation, is_generated
    FROM information_schema.columns 
    WHERE table_schema = ${schema} 
      AND table_name = ${table}
      AND is_generated = 'NEVER'
    ORDER BY ordinal_position
  `;
  const cols = rows.map((r: any) => r.column_name);
  const hasIdentity = rows.some((r: any) => r.identity_generation === "ALWAYS");
  return { cols, hasIdentity };
}

async function main() {
  const cfg = config();
  const remoteUrl =
    process.env.SUPABASE_DB_URL ||
    "postgresql://postgres.hhciuruwxdubswuunlrz:Ytsabi79033@aws-0-ap-southeast-2.pooler.supabase.com:5432/postgres?sslmode=require";

  const localUrl = localDatabaseUrl("salescrm", cfg);

  console.log("Connecting to production Supabase via pooler...");
  const remoteSql = postgres(remoteUrl, { ...getDbOptions(remoteUrl), max: 1, onnotice: () => {} });

  console.log("Connecting to local PostgreSQL database...");
  const localSql = postgres(localUrl, { max: 1, onnotice: () => {} });

  try {
    await localSql.unsafe("SET session_replication_role = 'replica'");

    // Truncate in reverse order
    for (const fullTable of [...TABLES].reverse()) {
      await localSql.unsafe(`TRUNCATE TABLE ${fullTable} CASCADE`).catch(() => {});
    }

    for (const fullTable of TABLES) {
      const [schema, table] = fullTable.split(".");
      console.log(`Syncing ${fullTable}...`);

      const { cols: localCols, hasIdentity } = await getTableInfo(localSql, schema, table);
      if (localCols.length === 0) {
        console.warn(`  Skipping ${fullTable} (no columns found locally)`);
        continue;
      }

      if (hasIdentity) {
        await localSql.unsafe(`ALTER TABLE ${schema}.${table} ALTER COLUMN id SET GENERATED BY DEFAULT`).catch(() => {});
      }

      const rows = await remoteSql.unsafe(`SELECT * FROM ${fullTable}`).catch((e) => {
        console.warn(`  Skipping ${fullTable} (remote query error: ${e.message})`);
        return [];
      });

      if (rows.length === 0) {
        console.log(`  ${fullTable}: 0 rows on remote.`);
        continue;
      }

      const chunkSize = 200;
      for (let i = 0; i < rows.length; i += chunkSize) {
        const chunk = rows.slice(i, i + chunkSize).map((r) => {
          const item: Record<string, any> = {};
          for (const col of localCols) {
            if (col in r) {
              item[col] = r[col];
            }
          }
          return item;
        });

        await localSql`INSERT INTO ${localSql(schema)}.${localSql(table)} ${localSql(chunk)}`;
      }

      if (hasIdentity) {
        await localSql.unsafe(`ALTER TABLE ${schema}.${table} ALTER COLUMN id SET GENERATED ALWAYS`).catch(() => {});
      }

      console.log(`  ✓ Synced ${rows.length} rows into ${fullTable}`);
    }

    // Set demo bcrypt password hash ($2b$10$... / Admin123!demo) for users without passwords
    const demoHash = "$2b$10$CwTycUXWue0Thq9StjUM0uJ8DPLKXt1FYlwYpaW3nB2J1vNnB0k1S";
    await localSql.unsafe(`
      UPDATE auth.users
      SET encrypted_password = '${demoHash}'
      WHERE encrypted_password IS NULL OR encrypted_password = ''
    `);

    // Ensure fallback admin@example.com exists in local database for convenience
    const localAdminId = "38759cb9-3224-4fab-b907-9461a30a176d";
    await localSql.unsafe(`
      INSERT INTO auth.users (id, email, encrypted_password)
      VALUES ('${localAdminId}', 'admin@example.com', '${demoHash}')
      ON CONFLICT (id) DO NOTHING
    `);
    await localSql.unsafe(`
      INSERT INTO public.profiles (id, email, full_name, role, time_zone, active)
      VALUES ('${localAdminId}', 'admin@example.com', 'Alex Morgan', 'admin', 'America/Chicago', true)
      ON CONFLICT (id) DO NOTHING
    `);

    // Reset all sequences to MAX(column) so new inserts do not conflict with existing IDs
    const seqCols = await localSql`
      SELECT
        c.table_schema,
        c.table_name,
        c.column_name,
        pg_get_serial_sequence(format('%I.%I', c.table_schema, c.table_name), c.column_name) AS seq
      FROM information_schema.columns c
      WHERE c.table_schema IN ('public', 'auth')
    `;
    for (const r of seqCols) {
      if (!r.seq) continue;
      await localSql.unsafe(
        `SELECT setval('${r.seq}', COALESCE((SELECT MAX("${r.column_name}") FROM "${r.table_schema}"."${r.table_name}"), 1))`
      );
    }

    await localSql.unsafe("SET session_replication_role = 'origin'");
    console.log("\nSuccess! All production data has been synced to your local database.");
  } finally {
    await remoteSql.end();
    await localSql.end();
  }
}

main().catch((err) => {
  console.error("Failed to pull production data:", err);
  process.exit(1);
});
